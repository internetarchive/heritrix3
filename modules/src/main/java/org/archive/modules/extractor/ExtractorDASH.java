/**
 * Extracts the media segment URLs from MPEG-DASH manifests (MPD files), so that the audio and
 * video of DASH streams can be archived and replayed.
 *
 * <p>Handles responses with the content type {@code application/dash+xml} and responses for
 * URLs ending in {@code .mpd}. Whether a response is actually a DASH manifest is decided by its
 * root element, so other documents are left for later extractors.
 *
 * <p>For each Representation (one encoding of a stream, such as a resolution or bitrate) the
 * extractor resolves the nested {@code BaseURL} elements and extracts as embedded links:
 * <ul>
 * <li>the initialization segment, from {@code Initialization} or the
 * {@code initialization} attribute of {@code SegmentTemplate}</li>
 * <li>each {@code SegmentURL} of a {@code SegmentList}</li>
 * <li>the media segments generated by a {@code SegmentTemplate}, either from its
 * {@code SegmentTimeline} or from its segment {@code duration} and the length of the
 * Period</li>
 * <li>the {@code BaseURL} itself, for Representations that are a single file</li>
 * </ul>
 *
 * <p>Live streams (manifests with {@code type="dynamic"}) are skipped. Only the first
 * {@code BaseURL} at each level is used; alternative BaseURLs, such as other CDNs, are ignored.
 *
 * <p>A long video with many Representations can have tens of thousands of segments. At most
 * {@code maxUrlsPerManifest} URLs are generated from one manifest, and the {@code maxOutlinks}
 * limit of the crawl's extractor parameters also applies.
 */
public class ExtractorDASH extends ContentExtractor {

    private static final Logger logger = Logger.getLogger(ExtractorDASH.class.getName());

    static final String DASH_NS = "urn:mpeg:dash:schema:mpd:2011";

    static final LinkContext BASE_URL = new LinkContext.SimpleLinkContext("BaseURL");
    static final LinkContext INITIALIZATION =
            new LinkContext.SimpleLinkContext("Initialization/@sourceURL");
    static final LinkContext SEGMENT_URL =
            new LinkContext.SimpleLinkContext("SegmentURL/@media");
    static final LinkContext TEMPLATE_INITIALIZATION =
            new LinkContext.SimpleLinkContext("SegmentTemplate/@initialization");
    static final LinkContext TEMPLATE_MEDIA =
            new LinkContext.SimpleLinkContext("SegmentTemplate/@media");

    private static final String SEGMENT_BASE = "SegmentBase";
    private static final String SEGMENT_LIST = "SegmentList";
    private static final String SEGMENT_TEMPLATE = "SegmentTemplate";

    /** $Identifier$ or $Identifier%0[width]d$ in a SegmentTemplate. $$ is an escaped $. */
    private static final Pattern TEMPLATE_IDENTIFIER =
            Pattern.compile("\\$([A-Za-z]*)(?:%0([0-9]+)d)?\\$");

    /** Widths beyond this are treated as invalid rather than padding to absurd lengths. */
    private static final int MAX_TEMPLATE_WIDTH = 32;

    /** xs:duration, as used for MPD and Period durations and start times. */
    private static final Pattern XS_DURATION = Pattern.compile(
            "P(?:([0-9.]+)Y)?(?:([0-9.]+)M)?(?:([0-9.]+)D)?" +
            "(?:T(?:([0-9.]+)H)?(?:([0-9.]+)M)?(?:([0-9.]+)S)?)?");

    private static final XMLInputFactory INPUT_FACTORY = ExtractorSVG.newInputFactory();

    {
        setMaxSizeToParse(10 * 1024 * 1024L); // 10MB
    }
    public long getMaxSizeToParse() {
        return (Long) kp.get("maxSizeToParse");
    }
    /**
     * The maximum number of bytes of a manifest to parse, after any content encoding such as
     * gzip is decoded. Segments described after this point are not extracted.
     */
    public void setMaxSizeToParse(long maxSizeToParse) {
        kp.put("maxSizeToParse", maxSizeToParse);
    }

    {
        setMaxUrlsPerManifest(6000);
    }
    public int getMaxUrlsPerManifest() {
        return (Integer) kp.get("maxUrlsPerManifest");
    }
    /**
     * The maximum number of URLs to generate from one manifest. Segments beyond this are not
     * extracted. This bounds the work done for manifests with very long or malformed segment
     * timelines. The extractor parameters' {@code maxOutlinks} limit also applies, so raise both
     * to capture long videos in full.
     */
    public void setMaxUrlsPerManifest(int maxUrlsPerManifest) {
        kp.put("maxUrlsPerManifest", maxUrlsPerManifest);
    }

    @Override
    protected boolean shouldExtract(CrawlURI curi) {
        if (curi.hasContentType("application/dash+xml")
                || curi.hasContentType("video/vnd.mpeg.dash.mpd")) {
            return true;
        }
        // manifests are often served as generic XML or binary content types
        try {
            String path = curi.getUURI().getPath();
            return path != null && path.toLowerCase(Locale.ROOT).endsWith(".mpd");
        } catch (URIException e) {
            return false;
        }
    }

    @Override
    protected boolean innerExtract(CrawlURI curi) {
        Element mpd = null;
        try (BoundedInputStream in = BoundedInputStream.builder()
                .setInputStream(curi.getRecorder().getContentReplayInputStream())
                .setMaxCount(getMaxSizeToParse())
                .get()) {
            try {
                XMLStreamReader reader;
                if (curi.containsContentTypeCharsetDeclaration()) {
                    reader = INPUT_FACTORY.createXMLStreamReader(in,
                            curi.getRecorder().getCharset().name());
                } else {
                    reader = INPUT_FACTORY.createXMLStreamReader(in);
                }
                try {
                    mpd = readRootElement(reader);
                    if (mpd == null) {
                        return false;
                    }
                    if ("dynamic".equals(mpd.attribute("type"))) {
                        if (logger.isLoggable(Level.FINE)) {
                            logger.fine("Skipping dynamic (live) DASH manifest " + curi);
                        }
                        return true;
                    }
                    readDescendants(reader, mpd);
                } finally {
                    reader.close();
                }
            } catch (XMLStreamException e) {
                if (mpd == null) {
                    // not well-formed up to the root element, so leave it to other extractors
                    return false;
                }
                // extract what was read before the error
                if (in.getRemaining() == 0) {
                    if (logger.isLoggable(Level.FINE)) {
                        logger.fine("Stopped parsing DASH manifest at maxSizeToParse: " + curi);
                    }
                } else {
                    if (logger.isLoggable(Level.FINE)) {
                        logger.fine("Error parsing DASH manifest " + curi + ": " + e.getMessage());
                    }
                    curi.getNonFatalFailures().add(e);
                }
            }
        } catch (IOException e) {
            logger.log(Level.WARNING, "Failed reading content of " + curi, e);
            curi.getNonFatalFailures().add(e);
            return false;
        }
        new Extraction(curi).extract(mpd);
        return true;
    }

    /**
     * Reads up to the root element.
     *
     * @return the root element, without its descendants, or null if it isn't a DASH {@code <MPD>}
     */
    protected Element readRootElement(XMLStreamReader reader) throws XMLStreamException {
        while (reader.hasNext()) {
            if (reader.next() == XMLStreamConstants.START_ELEMENT) {
                String namespace = namespace(reader);
                if (!reader.getLocalName().equals("MPD")
                        || !(namespace.equals(DASH_NS) || namespace.isEmpty())) {
                    return null;
                }
                return new Element(reader, namespace);
            }
        }
        return null;
    }

    /**
     * Reads the descendants of the root element into a tree, keeping only elements in the
     * root's namespace. The text of a {@code BaseURL} is only kept once its end tag is read, so
     * that a URL cut off by an XML error is not used.
     */
    protected void readDescendants(XMLStreamReader reader, Element root)
            throws XMLStreamException {
        Deque<Element> open = new ArrayDeque<>();
        open.push(root);
        int foreignDepth = 0;
        StringBuilder text = null;
        while (reader.hasNext() && !open.isEmpty()) {
            switch (reader.next()) {
                case XMLStreamConstants.START_ELEMENT:
                    if (foreignDepth > 0 || !namespace(reader).equals(root.namespace)) {
                        foreignDepth++;
                        break;
                    }
                    Element element = new Element(reader, root.namespace);
                    open.peek().children.add(element);
                    open.push(element);
                    text = element.name.equals("BaseURL") ? new StringBuilder() : null;
                    break;
                case XMLStreamConstants.CHARACTERS:
                case XMLStreamConstants.CDATA:
                    if (text != null && foreignDepth == 0) {
                        text.append(reader.getText());
                    }
                    break;
                case XMLStreamConstants.END_ELEMENT:
                    if (foreignDepth > 0) {
                        foreignDepth--;
                        break;
                    }
                    Element closed = open.pop();
                    if (text != null) {
                        closed.text = text.toString().trim();
                        text = null;
                    }
                    break;
                default:
                    break;
            }
        }
    }

    private static String namespace(XMLStreamReader reader) {
        String namespace = reader.getNamespaceURI();
        return namespace == null ? "" : namespace;
    }

    /**
     * An element of the manifest, with its attributes in no namespace.
     */
    protected static class Element {
        final String name;
        final String namespace;
        final Map<String, String> attributes = new HashMap<>();
        final List<Element> children = new ArrayList<>();
        /** The trimmed text content, for a {@code BaseURL} whose end tag was read */
        String text;

        Element(XMLStreamReader reader, String namespace) {
            this.name = reader.getLocalName();
            this.namespace = namespace;
            for (int i = 0; i < reader.getAttributeCount(); i++) {
                String attributeNamespace = reader.getAttributeNamespace(i);
                if (attributeNamespace == null || attributeNamespace.isEmpty()) {
                    attributes.put(reader.getAttributeLocalName(i),
                            reader.getAttributeValue(i).trim());
                }
            }
        }

        String attribute(String name) {
            return attributes.get(name);
        }

        Element child(String name) {
            for (Element child : children) {
                if (child.name.equals(name)) {
                    return child;
                }
            }
            return null;
        }

        List<Element> children(String name) {
            List<Element> result = new ArrayList<>();
            for (Element child : children) {
                if (child.name.equals(name)) {
                    result.add(child);
                }
            }
            return result;
        }
    }

    /**
     * The state of extracting links from one manifest.
     */
    protected class Extraction {
        private final CrawlURI curi;
        private final int maxOutlinks;
        private final Set<String> added = new HashSet<>();
        private int remaining;

        Extraction(CrawlURI curi) {
            this.curi = curi;
            this.maxOutlinks = getExtractorParameters().getMaxOutlinks();
            this.remaining = getMaxUrlsPerManifest();
        }

        void extract(Element mpd) {
            UURI mpdBase = resolveBaseURL(curi.getBaseURI(), mpd);
            List<Element> periods = mpd.children("Period");
            double[] periodDurations = periodDurations(mpd, periods);
            for (int i = 0; i < periods.size(); i++) {
                Element period = periods.get(i);
                UURI periodBase = resolveBaseURL(mpdBase, period);
                for (Element adaptationSet : period.children("AdaptationSet")) {
                    UURI adaptationSetBase = resolveBaseURL(periodBase, adaptationSet);
                    for (Element representation : adaptationSet.children("Representation")) {
                        UURI representationBase = resolveBaseURL(adaptationSetBase,
                                representation);
                        extractRepresentation(representationBase,
                                List.of(representation, adaptationSet, period),
                                periodDurations[i]);
                        if (remaining <= 0) {
                            if (logger.isLoggable(Level.FINE)) {
                                logger.fine("Stopped at maxUrlsPerManifest: " + curi);
                            }
                            return;
                        }
                    }
                }
            }
        }

        /**
         * @param levels the Representation, AdaptationSet and Period, lowest level first
         * @param periodDuration in seconds, or NaN if unknown
         */
        void extractRepresentation(UURI base, List<Element> levels, double periodDuration) {
            // segment information is inherited, and the lowest level that has any decides the
            // kind of addressing
            String kind = null;
            for (Element level : levels) {
                for (String candidate : new String[] {SEGMENT_TEMPLATE, SEGMENT_LIST,
                        SEGMENT_BASE}) {
                    if (level.child(candidate) != null) {
                        kind = candidate;
                        break;
                    }
                }
                if (kind != null) {
                    break;
                }
            }
            List<Element> segmentInfo = new ArrayList<>();
            if (kind != null) {
                for (Element level : levels) {
                    Element element = level.child(kind);
                    if (element != null) {
                        segmentInfo.add(element);
                    }
                }
            }

            if (kind == null || kind.equals(SEGMENT_BASE)) {
                // the whole Representation is the one file at the BaseURL
                add(base, "", BASE_URL);
                addInitialization(base, segmentInfo);
            } else if (kind.equals(SEGMENT_LIST)) {
                addInitialization(base, segmentInfo);
                for (Element segmentList : segmentInfo) {
                    List<Element> segmentUrls = segmentList.children("SegmentURL");
                    if (segmentUrls.isEmpty()) {
                        continue;
                    }
                    for (Element segmentUrl : segmentUrls) {
                        // without @media, the segment is a byte range of the BaseURL
                        String media = segmentUrl.attribute("media");
                        if (!add(base, media == null ? "" : media, SEGMENT_URL)) {
                            return;
                        }
                    }
                    break;
                }
            } else {
                extractTemplate(base, levels.get(0), segmentInfo, periodDuration);
            }
        }

        void addInitialization(UURI base, List<Element> segmentInfo) {
            Element initialization = inheritedChild(segmentInfo, "Initialization");
            if (initialization != null) {
                // without @sourceURL, it's a byte range of the BaseURL
                String sourceURL = initialization.attribute("sourceURL");
                add(base, sourceURL == null ? "" : sourceURL, INITIALIZATION);
            }
        }

        void extractTemplate(UURI base, Element representation, List<Element> templates,
                double periodDuration) {
            String id = representation.attribute("id");
            String bandwidth = representation.attribute("bandwidth");

            String initialization = inheritedAttribute(templates, "initialization");
            if (initialization != null) {
                String url = expandTemplate(initialization, id, bandwidth, null, null);
                if (url != null) {
                    add(base, url, TEMPLATE_INITIALIZATION);
                }
            } else {
                addInitialization(base, templates);
            }

            String media = inheritedAttribute(templates, "media");
            if (media == null) {
                return;
            }
            long timescale = parseLong(inheritedAttribute(templates, "timescale"), 1);
            if (timescale <= 0) {
                timescale = 1;
            }
            long number = parseLong(inheritedAttribute(templates, "startNumber"), 1);
            long presentationTimeOffset =
                    parseLong(inheritedAttribute(templates, "presentationTimeOffset"), 0);
            // the end of the Period in the template's timescale
            long periodEnd = Double.isNaN(periodDuration) ? -1
                    : presentationTimeOffset
                            + (long) Math.ceil(periodDuration * timescale - 1e-6);

            Element timeline = inheritedChild(templates, "SegmentTimeline");
            if (timeline != null) {
                List<Element> segments = timeline.children("S");
                long time = 0;
                for (int i = 0; i < segments.size(); i++) {
                    Element segment = segments.get(i);
                    time = parseLong(segment.attribute("t"), time);
                    long duration = parseLong(segment.attribute("d"), 0);
                    if (duration <= 0) {
                        return;
                    }
                    long repeat = parseLong(segment.attribute("r"), 0);
                    long count;
                    if (repeat >= 0) {
                        count = repeat + 1;
                    } else {
                        // a negative repeat count repeats until the next S or the Period's end
                        long end = -1;
                        if (i + 1 < segments.size()) {
                            end = parseLong(segments.get(i + 1).attribute("t"), -1);
                        }
                        if (end < 0) {
                            end = periodEnd;
                        }
                        count = end > time ? (end - time - 1) / duration + 1 : 1;
                    }
                    for (long j = 0; j < count; j++) {
                        if (!addSegment(base, media, id, bandwidth, number, time)) {
                            return;
                        }
                        number++;
                        time += duration;
                    }
                }
                return;
            }

            long duration = parseLong(inheritedAttribute(templates, "duration"), 0);
            long endNumber = parseLong(inheritedAttribute(templates, "endNumber"), -1);
            long count;
            if (duration <= 0) {
                // without a duration, the Representation has a single segment
                count = 1;
            } else if (endNumber >= number) {
                count = endNumber - number + 1;
            } else if (periodEnd >= 0) {
                count = (periodEnd - presentationTimeOffset + duration - 1) / duration;
            } else {
                if (logger.isLoggable(Level.FINE)) {
                    logger.fine("Unknown number of segments for " + media + " in " + curi);
                }
                return;
            }
            long time = presentationTimeOffset;
            for (long j = 0; j < count; j++) {
                if (!addSegment(base, media, id, bandwidth, number, time)) {
                    return;
                }
                number++;
                time += duration;
            }
        }

        /**
         * @return false if no more URLs should be generated
         */
        boolean addSegment(UURI base, String media, String id, String bandwidth, long number,
                long time) {
            String url = expandTemplate(media, id, bandwidth, number, time);
            if (url == null) {
                return false; // the template is invalid for every segment
            }
            return add(base, url, TEMPLATE_MEDIA);
        }

        /**
         * Adds a link to the given URL, relative to the base. Counts towards
         * {@code maxUrlsPerManifest} even if it's a duplicate.
         *
         * @return false if no more URLs should be generated
         */
        boolean add(UURI base, String url, LinkContext context) {
            if (remaining <= 0) {
                return false;
            }
            remaining--;
            if (UriUtils.isDataUri(url)) {
                return true;
            }
            try {
                UURI dest = UURIFactory.getInstance(base, url);
                String destString = dest.toString();
                if (destString.equals(curi.getUURI().toString()) || !added.add(destString)) {
                    return true;
                }
                if (addRelativeTo(curi, maxOutlinks, base, url, context, Hop.EMBED) != null) {
                    numberOfLinksExtracted.incrementAndGet();
                }
            } catch (URIException e) {
                logUriError(e, base, url);
            }
            return true;
        }

        UURI resolveBaseURL(UURI base, Element element) {
            for (Element baseURL : element.children("BaseURL")) {
                if (baseURL.text == null || baseURL.text.isEmpty()) {
                    continue;
                }
                try {
                    return UURIFactory.getInstance(base, baseURL.text);
                } catch (URIException e) {
                    logUriError(e, base, baseURL.text);
                }
                break;
            }
            return base;
        }
    }

    /**
     * Expands the identifiers in a SegmentTemplate {@code media} or {@code initialization}
     * attribute.
     *
     * @param number the segment number, or null if not known
     * @param time the segment start time, or null if not known
     * @return the URL, or null if the template is invalid or uses a value that isn't known
     */
    static String expandTemplate(String template, String representationId, String bandwidth,
            Long number, Long time) {
        Matcher matcher = TEMPLATE_IDENTIFIER.matcher(template);
        StringBuilder result = new StringBuilder();
        while (matcher.find()) {
            String identifier = matcher.group(1);
            String width = matcher.group(2);
            String value;
            switch (identifier) {
                case "":
                    value = width == null ? "$" : null;
                    break;
                case "RepresentationID":
                    value = width == null ? representationId : null;
                    break;
                case "Number":
                    value = format(number, width);
                    break;
                case "Time":
                    value = format(time, width);
                    break;
                case "Bandwidth":
                    long bits = parseLong(bandwidth, -1);
                    value = bits < 0 ? null : format(bits, width);
                    break;
                default:
                    value = null;
                    break;
            }
            if (value == null) {
                return null;
            }
            matcher.appendReplacement(result, Matcher.quoteReplacement(value));
        }
        matcher.appendTail(result);
        return result.toString();
    }

    private static String format(Long value, String width) {
        if (value == null) {
            return null;
        }
        String digits = Long.toString(value);
        if (width == null) {
            return digits;
        }
        int padding;
        try {
            padding = Integer.parseInt(width);
        } catch (NumberFormatException e) {
            return null;
        }
        if (padding > MAX_TEMPLATE_WIDTH) {
            return null;
        }
        StringBuilder padded = new StringBuilder();
        for (int i = digits.length(); i < padding; i++) {
            padded.append('0');
        }
        return padded.append(digits).toString();
    }

    private static String inheritedAttribute(List<Element> levels, String name) {
        for (Element level : levels) {
            String value = level.attribute(name);
            if (value != null) {
                return value;
            }
        }
        return null;
    }

    private static Element inheritedChild(List<Element> levels, String name) {
        for (Element level : levels) {
            Element child = level.child(name);
            if (child != null) {
                return child;
            }
        }
        return null;
    }

    private static long parseLong(String value, long defaultValue) {
        if (value == null) {
            return defaultValue;
        }
        try {
            return Long.parseLong(value);
        } catch (NumberFormatException e) {
            return defaultValue;
        }
    }

    /**
     * Works out the duration of each Period from the Periods' start times and durations and the
     * MPD's mediaPresentationDuration.
     *
     * @return the durations in seconds, NaN where unknown
     */
    static double[] periodDurations(Element mpd, List<Element> periods) {
        int n = periods.size();
        double[] starts = new double[n];
        double[] durations = new double[n];
        for (int i = 0; i < n; i++) {
            durations[i] = parseDuration(periods.get(i).attribute("duration"));
            starts[i] = parseDuration(periods.get(i).attribute("start"));
            if (Double.isNaN(starts[i])) {
                starts[i] = i == 0 ? 0 : starts[i - 1] + durations[i - 1];
            }
        }
        double total = parseDuration(mpd.attribute("mediaPresentationDuration"));
        for (int i = 0; i < n; i++) {
            if (Double.isNaN(durations[i])) {
                durations[i] = (i + 1 < n ? starts[i + 1] : total) - starts[i];
            }
            if (!(durations[i] > 0)) {
                durations[i] = Double.NaN;
            }
        }
        return durations;
    }

    /**
     * Parses an xs:duration, counting a year as 365 days and a month as 30 days.
     *
     * @return the duration in seconds, or NaN if it's missing or invalid
     */
    static double parseDuration(String value) {
        if (value == null) {
            return Double.NaN;
        }
        Matcher matcher = XS_DURATION.matcher(value);
        if (!matcher.matches() || value.endsWith("P") || value.endsWith("T")) {
            return Double.NaN;
        }
        double[] unitSeconds = {365 * 86400, 30 * 86400, 86400, 3600, 60, 1};
        double seconds = 0;
        try {
            for (int i = 0; i < unitSeconds.length; i++) {
                String group = matcher.group(i + 1);
                if (group != null) {
                    seconds += Double.parseDouble(group) * unitSeconds[i];
                }
            }
        } catch (NumberFormatException e) {
            return Double.NaN;
        }
        return seconds;
    }
}
